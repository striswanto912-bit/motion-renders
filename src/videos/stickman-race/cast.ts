/** blue's cartwheels: roll 0 -> 2*PI over 0.6 s at each cartwheel (the "somersaults" at 17.7-18.2 s, second ~19.5 s) */
const CARTWHEELS: [number, number][] = [[17.5, 18.1], [19.5, 20.1]];
const wheelOf = (t: number) => {
  for (const [a, b] of CARTWHEELS) if (t >= a && t < b) { const u = (t - a) / (b - a); return { roll: u * Math.PI * 2, hop: 0.45 * Math.sin(Math.PI * u) }; }
  return { roll: 0, hop: 0 };
};

